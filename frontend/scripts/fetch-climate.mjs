// Builds one climate file per city in src/data/climate/ from Open-Meteo historical data.
// Run with: node scripts/fetch-climate.mjs
// Each city file = shared.json + the city's own values. The city values come from May–June, 2015–2024:
//   outdoorPeakC           median across years of the hottest hour
//   outdoorNightLowC       median of all daily minimum temperatures
//   relHumidityAfternoonPct median across years of the mean humidity at 14:00
//   solarPeakWm2.roof      median across years of the highest horizontal solar radiation
// The shared constants are copied into every city file, so the engine reads one object per city.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const climateDir = path.join(here, "..", "src", "data", "climate");

const START = "2015-05-01";
const END = "2024-06-30";
const MONTHS = [5, 6];

const CITIES = [
  { id: "delhi", name: "Delhi", region: "Delhi NCR", lat: 28.6139, lon: 77.209 },
  { id: "jaipur", name: "Jaipur", region: "Rajasthan", lat: 26.9124, lon: 75.7873 },
  { id: "ahmedabad", name: "Ahmedabad", region: "Gujarat", lat: 23.0225, lon: 72.5714 },
  { id: "kochi", name: "Kochi", region: "Kerala", lat: 9.9312, lon: 76.2673 },
];

const median = (values) => {
  const s = [...values].sort((a, b) => a - b);
  const mid = s.length / 2;
  return s.length % 2 ? s[Math.floor(mid)] : (s[mid - 1] + s[mid]) / 2;
};

async function fetchHourly(city) {
  const url =
    `https://archive-api.open-meteo.com/v1/archive?latitude=${city.lat}&longitude=${city.lon}` +
    `&start_date=${START}&end_date=${END}` +
    `&hourly=temperature_2m,shortwave_radiation,relative_humidity_2m&timezone=Asia%2FKolkata`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Open-Meteo request for ${city.name} failed: ${res.status}`);
  return (await res.json()).hourly;
}

function summarise(hourly) {
  const years = {};
  const dailyMins = [];
  const days = {};

  hourly.time.forEach((stamp, i) => {
    const year = Number(stamp.slice(0, 4));
    const month = Number(stamp.slice(5, 7));
    if (!MONTHS.includes(month)) return;
    const temp = hourly.temperature_2m[i];
    const y = (years[year] ??= { temps: [], solar: [], humidityAt14: [] });
    y.temps.push(temp);
    y.solar.push(hourly.shortwave_radiation[i]);
    if (stamp.slice(11, 13) === "14") y.humidityAt14.push(hourly.relative_humidity_2m[i]);

    const day = stamp.slice(0, 10);
    days[day] = Math.min(days[day] ?? Infinity, temp);
  });

  for (const v of Object.values(days)) dailyMins.push(v);

  const annual = Object.values(years);
  return {
    outdoorPeakC: Number(median(annual.map((y) => Math.max(...y.temps))).toFixed(1)),
    outdoorNightLowC: Number(median(dailyMins).toFixed(1)),
    relHumidityAfternoonPct: Math.round(median(annual.map((y) => y.humidityAt14.reduce((s, h) => s + h, 0) / y.humidityAt14.length))),
    roofSolarWm2: Math.round(median(annual.map((y) => Math.max(...y.solar)))),
    years: Object.keys(years).length,
  };
}

const shared = JSON.parse(await fs.readFile(path.join(climateDir, "shared.json"), "utf8"));

for (const city of CITIES) {
  const stats = summarise(await fetchHourly(city));
  const out = {
    _note: `Generated by scripts/fetch-climate.mjs for ${city.name}. Do not edit by hand. Edit shared.json or the script instead.`,
    location: `${city.name}, ${city.region}`,
    site: { id: city.id, name: city.name, region: city.region, lat: city.lat, lon: city.lon },
    source: {
      provider: "Open-Meteo Historical Weather API",
      url: "https://archive-api.open-meteo.com/v1/archive",
      period: `${START} to ${END}, May and June only`,
      years: stats.years,
      method: "Medians across years of annual peaks, as described in scripts/fetch-climate.mjs.",
      fetchedOn: new Date().toISOString().slice(0, 10),
    },
    outdoorPeakC: stats.outdoorPeakC,
    outdoorNightLowC: stats.outdoorNightLowC,
    relHumidityAfternoonPct: stats.relHumidityAfternoonPct,
    ...shared,
    solarPeakWm2: { ...shared.solarPeakWm2, roof: stats.roofSolarWm2 },
  };
  await fs.writeFile(path.join(climateDir, `${city.id}.json`), JSON.stringify(out, null, 2) + "\n");
  console.log(`${city.name}: peak ${out.outdoorPeakC} °C, night low ${out.outdoorNightLowC} °C, RH14 ${out.relHumidityAfternoonPct}%, roof ${out.solarPeakWm2.roof} W/m²`);
}
